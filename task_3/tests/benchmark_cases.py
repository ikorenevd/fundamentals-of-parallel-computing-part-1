#!/usr/bin/env python3
"""Deterministic input catalog for the task_3 timing runner.

Usage::

    python3 tests/benchmark_cases.py --output-dir /tmp/matrices
    python3 tests/benchmark_cases.py --profile quick --output-dir /tmp/matrices
    python3 tests/benchmark_cases.py --profile full --output-dir /tmp/matrices
    python3 tests/benchmark_cases.py --self-test

stdout contains only a TSV manifest, without a header. Each row has seven
fields: name, n, m, r, s, absolute filename (or ``<none>``), expectation.
Names and case order stay the same between runs. Generated matrix contents
are independent of the output directory and do not use random numbers.

``solved`` means a finite successful solution is expected; ``unsolved`` means
the solver should report failure; ``error`` means argument/input rejection
before the final report. ``any`` deliberately allows numerical conditioning
or block-pivot limitations to determine the outcome. In particular, a
nonsingular matrix need not contain an invertible aligned block of size m.
The catalog does not change these limitations of the implementation.

The default full profile has 535 cases. The optional quick profile has 295
small formula, file, format, and argument cases.
The full profile includes quick plus larger formula and file benchmarks,
including formula matrices of size 4000. These large matrices are
generated by the solver itself; the catalog does not write their data files.
The scalar block benchmarks (m=1) use n=2000 instead of n=4000.
Formula s=4 (Hilbert matrices) is included only for n <= 15.
Only Python's standard library is required.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import sys
import tempfile
from typing import Callable


NO_FILE = "<none>"
EXPECTATIONS = {"solved", "unsolved", "error", "any"}
TEST_DATA = Path(__file__).resolve().parents[1] / "test_data"


@dataclass(frozen=True)
class Case:
    name: str
    n: int
    m: int
    r: int
    s: int
    filename: Path | None
    expectation: str

    def manifest_line(self) -> str:
        filename = str(self.filename) if self.filename is not None else NO_FILE
        return "\t".join(map(str, (
            self.name, self.n, self.m, self.r, self.s, filename,
            self.expectation,
        )))


def _matrix(n: int, entry: Callable[[int, int], float]) -> list[list[float]]:
    return [[float(entry(i, j)) for j in range(n)] for i in range(n)]


def _dominant(n: int) -> list[list[float]]:
    """Dense, nonsymmetric, strictly row-diagonally dominant integer matrix."""
    matrix = _matrix(n, lambda i, j: ((i * 17 + j * 7 + 3) % 11) - 5)
    for i in range(n):
        matrix[i][i] = 2.0 + sum(abs(matrix[i][j]) for j in range(n) if j != i)
    return matrix


def _diagonal(n: int, diagonal: Callable[[int], float]) -> list[list[float]]:
    return _matrix(n, lambda i, j: diagonal(i) if i == j else 0.0)


def _permuted(matrix: list[list[float]], rows: list[int],
              columns: list[int]) -> list[list[float]]:
    return [[matrix[i][j] for j in columns] for i in rows]


def _scaled(matrix: list[list[float]], factor: float) -> list[list[float]]:
    return [[value * factor for value in row] for row in matrix]


def _write_matrix(path: Path, matrix: list[list[float]]) -> None:
    n = len(matrix)
    if n < 1 or any(len(row) != n for row in matrix):
        raise ValueError("A fixture must be a nonempty square matrix")
    path.write_text("".join(
        " ".join(format(value, ".17g") for value in row) + "\n"
        for row in matrix
    ), encoding="ascii")


def _formula_expectation(n: int, s: int) -> str:
    if s == 3 and n == 1:
        return "unsolved"
    # Hilbert matrices become threshold/rounding dependent at these sizes.
    if s == 4 and n >= 10:
        return "any"
    return "solved"


def generate_cases(output_dir: Path, profile: str = "full") -> list[Case]:
    """Write deterministic fixtures and return the ordered benchmark cases.

    Existing files are read from task_3/test_data, while generated files go
    into output_dir. The output directory may contain spaces, but TSV control
    characters in its absolute path are rejected. The default ``full`` is a strict
    extension of ``quick`` and keeps all quick case names in the same order.
    """
    if profile not in {"quick", "full"}:
        raise ValueError("profile must be quick or full")
    output_dir = Path(output_dir).resolve()
    if any(character in str(output_dir) for character in "\t\r\n"):
        raise ValueError("output directory must not contain tabs or newlines")
    output_dir.mkdir(parents=True, exist_ok=True)
    cases: list[Case] = []

    def add(name: str, n: int, m: int, r: int = 0, s: int = 0,
            filename: Path | None = None, expectation: str = "solved") -> None:
        cases.append(Case(name, n, m, r, s, filename, expectation))

    # Every formula exercises scalar/full blocks, partial blocks and m > n.
    for n in (1, 2, 3, 4, 5, 7, 8, 12):
        block_sizes = sorted({1, 2, 3, max(1, n // 2), max(1, n - 1), n, n + 1})
        # n=1 only needs 1 and m>n; larger m values add no distinct path.
        if n == 1:
            block_sizes = [1, 2]
        for s in range(1, 5):
            if s == 4 and n > 15:
                continue
            for m in block_sizes:
                add(f"formula_s{s}_n{n}_m{m}", n, m, s=s,
                    expectation=_formula_expectation(n, s))

    # Generated files have small, interpretable matrices rather than noise.
    # A profile adds matrix sizes, never modifies a quick fixture.
    fixtures: list[tuple[str, list[list[float]], str]] = [
        ("dominant_5", _dominant(5), "solved"),
        ("dominant_7", _dominant(7), "solved"),
        ("nonsymmetric_9", _dominant(9), "solved"),
        ("signed_diagonal_6", _diagonal(6, lambda i: (-1) ** i * (i + 1)), "solved"),
        ("signed_diagonal_7", _diagonal(7, lambda i: (-1) ** i * (i + 1)), "solved"),
        ("scaled_small_5", _scaled(_dominant(5), 1e-10), "solved"),
        ("scaled_large_5", _scaled(_dominant(5), 1e100), "solved"),
        ("tiny_diagonal_5", _diagonal(5, lambda i: (i + 1) * 1e-18), "unsolved"),
        ("extreme_scale_5", _scaled(_dominant(5), 1e200), "any"),
        ("symmetric_positive_6", _matrix(6, lambda i, j: 9 if i == j else 1 / (1 + abs(i - j))), "solved"),
        ("upper_triangular_5", _matrix(5, lambda i, j: i + 2 if i == j else (j - i) / 4 if j > i else 0), "solved"),
        ("lower_triangular_7", _matrix(7, lambda i, j: i + 2 if i == j else (i + j + 1) / 7 if j < i else 0), "solved"),
        ("row_permuted_6", _permuted(_dominant(6), [2, 3, 4, 5, 0, 1], list(range(6))), "solved"),
        ("column_permuted_6", _permuted(_dominant(6), list(range(6)), [2, 3, 4, 5, 0, 1]), "solved"),
        ("row_column_permuted_7", _permuted(_dominant(7), [6, 0, 4, 2, 5, 1, 3], [3, 6, 1, 5, 0, 4, 2]), "any"),
        ("block_pivot_4", _permuted(_diagonal(4, lambda i: i + 1), [2, 3, 0, 1], list(range(4))), "solved"),
        ("within_block_pivot_4", [[0., 2., 0., 0.], [3., 0., 0., 0.], [0., 0., 0., 5.], [0., 0., 7., 0.]], "solved"),
        ("no_invertible_block_4", _permuted(_diagonal(4, lambda i: 1), [0, 2, 1, 3], list(range(4))), "any"),
        ("cyclic_permutation_5", _permuted(_diagonal(5, lambda i: 1), [1, 2, 3, 4, 0], list(range(5))), "any"),
        ("zero_5", _matrix(5, lambda i, j: 0), "unsolved"),
        ("rank_one_6", _matrix(6, lambda i, j: (i + 1) * (j + 1)), "unsolved"),
        ("singular_diagonal_6", _diagonal(6, lambda i: i + 1 if i < 5 else 0), "unsolved"),
        ("duplicate_rows_5", _permuted(_dominant(5), [0, 1, 2, 3, 0], list(range(5))), "any"),
        ("duplicate_columns_5", _permuted(_dominant(5), list(range(5)), [0, 1, 2, 3, 0]), "any"),
        ("ill_conditioned_diagonal_6", _diagonal(6, lambda i: 10.0 ** (-3 * i)), "any"),
        ("nearly_dependent_4", [[1., 1., 1., 1.], [1., 1. + 1e-14, 1., 1.], [1., 1., 1. + 2e-14, 1.], [1., 1., 1., 1. + 3e-14]], "any"),
    ]
    for fixture_name, matrix, expectation in fixtures:
        filename = output_dir / f"{fixture_name}.txt"
        _write_matrix(filename, matrix)
        n = len(matrix)
        block_sizes = {1, 2, n}
        if fixture_name in {"dominant_5", "dominant_7", "signed_diagonal_7", "nonsymmetric_9"}:
            block_sizes.add(3)
        for m in sorted(block_sizes):
            case_expectation = expectation
            if fixture_name == "no_invertible_block_4":
                case_expectation = "unsolved" if m == 2 else "solved"
            if fixture_name == "cyclic_permutation_5" and m in {1, n}:
                case_expectation = "solved"
            add(f"file_{fixture_name}_m{m}", n, m, filename=filename,
                expectation=case_expectation)

    existing_valid = (
        ("scalar_1.txt", 1), ("identity_3.txt", 3),
        ("dense_4.txt", 4), ("mixed_3.txt", 3),
        ("matrix with spaces_2.txt", 2), ("invalid_separator_2.txt", 2),
    )
    for filename, n in existing_valid:
        short_name = re.sub(r"[^a-zA-Z0-9]+", "_", Path(filename).stem).strip("_")
        for m in sorted({1, 2, n + 1}):
            add(f"existing_{short_name}_m{m}", n, m,
                filename=TEST_DATA / filename)

    for filename in ("singular_3.txt", "zero_3.txt"):
        for m in (1, 2, 3):
            add(f"existing_{Path(filename).stem}_m{m}", 3, m,
                filename=TEST_DATA / filename, expectation="unsolved")

    # These errors must never be mistaken for successful zero-second solves.
    invalid_files = (
        ("invalid_empty.txt", 2), ("invalid_short_3.txt", 3),
        ("invalid_extra_2.txt", 2), ("invalid_text_2.txt", 2),
        ("invalid_suffix_2.txt", 2), ("invalid_nan_2.txt", 2),
        ("invalid_inf_2.txt", 2), ("invalid_overflow_2.txt", 2),
        ("invalid_rhs_overflow_3.txt", 3),
    )
    for filename, n in invalid_files:
        add(f"input_{Path(filename).stem}", n, 1,
            filename=TEST_DATA / filename, expectation="error")
    add("input_missing_file", 2, 1,
        filename=output_dir / "intentionally_missing_matrix.txt", expectation="error")
    add("input_wrong_dimension_short", 5, 2,
        filename=TEST_DATA / "dense_4.txt", expectation="error")
    add("input_wrong_dimension_extra", 3, 2,
        filename=TEST_DATA / "dense_4.txt", expectation="error")

    # Use the manifest's integer arguments to cover invalid CLI combinations.
    for name, n, m, r, s in (
        ("n_zero", 0, 1, 0, 1), ("n_negative", -1, 1, 0, 1),
        ("m_zero", 3, 0, 0, 1), ("m_negative", 3, -2, 0, 1),
        ("r_negative", 3, 1, -1, 1), ("s_negative", 3, 1, 0, -1),
        ("s_too_large", 3, 1, 0, 5), ("s_zero_without_file", 3, 1, 0, 0),
    ):
        add(f"cli_{name}", n, m, r, s, expectation="error")
    add("cli_formula_with_file", 3, 1, s=1,
        filename=TEST_DATA / "identity_3.txt", expectation="error")
    add("cli_negative_formula_with_file", 3, 1, s=-1,
        filename=TEST_DATA / "identity_3.txt", expectation="error")

    for r in (0, 1, 3, 5, 9):
        add(f"print_formula_n5_m2_r{r}", 5, 2, r, 1)
    for r in (1, 4, 9):
        add(f"print_file_n4_m3_r{r}", 4, 3, r,
            filename=TEST_DATA / "dense_4.txt")

    if profile == "full":
        for n in (32, 64, 127, 128, 256, 511, 512, 1024, 2000, 4000):
            # m=1 is costly because each scalar pivot scans the full tail.
            # Larger blocks add inverse costs; partial blocks remain covered.
            block_sizes = sorted({1, 8, 16, 31, 32, 64, n, n + 1})
            if n == 2000:
                block_sizes = [1]
            elif n == 4000:
                block_sizes.remove(1)
            for s in range(1, 5):
                if s == 4 and n > 15:
                    continue
                for m in block_sizes:
                    add(f"benchmark_formula_s{s}_n{n}_m{m}", n, m, s=s,
                        expectation=_formula_expectation(n, s))
        for n in (64, 127, 256):
            for kind, matrix in (
                ("dominant", _dominant(n)),
                ("signed_diagonal", _diagonal(n, lambda i: (-1) ** i * (i % 31 + 1))),
            ):
                filename = output_dir / f"benchmark_{kind}_{n}.txt"
                _write_matrix(filename, matrix)
                for m in (1, 8, 16, 31, 64):
                    add(f"benchmark_file_{kind}_n{n}_m{m}", n, m,
                        filename=filename)

    _validate_cases(cases)
    return cases


def _validate_cases(cases: list[Case]) -> None:
    names: set[str] = set()
    for case in cases:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", case.name):
            raise ValueError(f"unsafe case name: {case.name!r}")
        if case.name in names:
            raise ValueError(f"duplicate case name: {case.name}")
        names.add(case.name)
        if case.expectation not in EXPECTATIONS:
            raise ValueError(f"unknown expectation: {case.expectation}")
        if case.filename is not None:
            if not case.filename.is_absolute():
                raise ValueError(f"relative filename: {case.filename}")
            if any(character in str(case.filename) for character in "\t\r\n"):
                raise ValueError("matrix filenames must not contain tabs or newlines")
        if len(case.manifest_line().split("\t")) != 7:
            raise ValueError(f"invalid manifest row: {case.name}")


def _rank(matrix: list[list[float]]) -> int:
    """Independent elimination used only by catalog self-checks."""
    work = [row[:] for row in matrix]
    rows, columns = len(work), len(work[0])
    rank = 0
    for column in range(columns):
        if rank == rows:
            break
        pivot = max(range(rank, rows), key=lambda row: abs(work[row][column]))
        if abs(work[pivot][column]) < 1e-12:
            continue
        work[rank], work[pivot] = work[pivot], work[rank]
        for row in range(rank + 1, rows):
            factor = work[row][column] / work[rank][column]
            for j in range(column, columns):
                work[row][j] -= factor * work[rank][j]
        rank += 1
    return rank


def _self_test() -> None:
    with tempfile.TemporaryDirectory(prefix="task3 catalog ") as first:
        with tempfile.TemporaryDirectory(prefix="task3 catalog ") as second:
            a = generate_cases(Path(first), "quick")
            b = generate_cases(Path(second), "quick")
            assert 150 <= len(a) <= 320, len(a)
            # Locations differ, but identities, ordering and matrix bytes do not.
            assert [(c.name, c.n, c.m, c.r, c.s, c.expectation) for c in a] == [
                (c.name, c.n, c.m, c.r, c.s, c.expectation) for c in b
            ]
            for path in Path(first).glob("*.txt"):
                assert path.read_bytes() == (Path(second) / path.name).read_bytes()
            assert {c.s for c in a if c.s > 0 and c.expectation != "error"} == {1, 2, 3, 4}
            assert any(c.m > c.n > 0 for c in a)
            assert any(c.n > c.m > 1 and c.n % c.m for c in a)
            assert {c.expectation for c in a} == EXPECTATIONS
            dominant = _dominant(9)
            assert _rank(dominant) == 9
            assert any(dominant[i][j] != dominant[j][i] for i in range(9) for j in range(9))
            assert all(abs(dominant[i][i]) > sum(abs(dominant[i][j]) for j in range(9) if i != j) for i in range(9))
            block_limited = _permuted(_diagonal(4, lambda i: 1), [0, 2, 1, 3], list(range(4)))
            assert _rank(block_limited) == 4
            assert all(_rank([row[j:j + 2] for row in block_limited[i:i + 2]]) < 2 for i in (0, 2) for j in (0, 2))
            full = generate_cases(Path(second), "full")
            assert full[:len(b)] == b
            assert generate_cases(Path(second)) == full
            assert len(a) == 295
            assert len(full) == 535
            assert max(c.n for c in full) == 4000
            assert all(c.n <= 4000 for c in full)
            assert not any(c.s == 4 and c.n > 15 for c in full)
            assert any(c.s == 4 and 1 <= c.n <= 15 for c in full)
            assert not any(c.n == 4000 and c.m == 1 for c in full)
            scalar_cases = [c for c in full if c.n == 2000]
            assert len(scalar_cases) == 3
            assert {c.s for c in scalar_cases} == {1, 2, 3}
            assert all(c.m == 1 and c.r == 0 and c.filename is None for c in scalar_cases)
            for n in (4000,):
                large_cases = [c for c in full if c.n == n]
                assert len(large_cases) == 21
                assert {c.s for c in large_cases} == {1, 2, 3}
                for s in range(1, 4):
                    formula_cases = [c for c in large_cases if c.s == s]
                    assert {c.m for c in formula_cases} == {8, 16, 31, 32, 64, n, n + 1}
                assert n % 31 != 0
                assert all(c.r == 0 and c.filename is None for c in large_cases)
            assert not any("4000" in path.name or "8000" in path.name for path in Path(second).glob("*.txt"))
            assert all(len(c.manifest_line().split("\t")) == 7 for c in full)
    print(f"Catalog checks passed: {len(a)} quick cases, {len(full)} full cases.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--profile", choices=("quick", "full"), default="full")
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--self-test", action="store_true", help="verify catalog properties and deterministic fixtures")
    args = parser.parse_args()
    if args.self_test:
        _self_test()
        return 0
    if args.output_dir is None:
        parser.error("--output-dir is required unless --self-test is used")
    try:
        cases = generate_cases(args.output_dir, args.profile)
    except (OSError, ValueError) as error:
        print(f"Cannot generate test catalog: {error}", file=sys.stderr)
        return 1
    for case in cases:
        print(case.manifest_line())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
